bool leader_add_user(uint16_t keycode) {
    ++leaderCount;
    oled_set_cursor(0, 5 + leaderCount);
    switch (leaderCount) {
        case 1:
            oled_write_P(PSTR("1"), false);
            break;
        case 2:
            oled_write_P(PSTR("2"), false);
            break;
        case 3:
            oled_write_P(PSTR("3"), false);
            break;
        case 4:
            oled_write_P(PSTR("4"), false);
            break;
    }
    return false;
}

