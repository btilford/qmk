bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    os_variant_t os = detected_host_os();

    if (leaderCount > 0) {
        rgb_matrix_set_color(g_led_config.matrix_co[record->event.key.row][record->event.key.col], RGB_PURPLE);
    }

    switch (keycode) {
        case COPY_MAC:
            if (record->event.pressed) {
                if (os == OS_MACOS || os == OS_IOS) {
                    SEND_STRING(SS_LALT(SS_TAP(X_C)));
                } else {
                    SEND_STRING(SS_LCTL("c"));
                }
            }
            break;
        case PASTE_MAC:
            if (record->event.pressed) {
                if (os == OS_MACOS || os == OS_IOS) {
                    SEND_STRING(SS_LALT(SS_TAP(X_V)));
                } else {
                    SEND_STRING(SS_LCTL("v"));
                }
            }
            break;
        case CUT_MAC:
            if (record->event.pressed) {
                if (os == OS_MACOS || os == OS_IOS) {
                    SEND_STRING(SS_LALT(SS_TAP(X_X)));
                } else {
                    SEND_STRING(SS_LCTL("x"));
                }
            }
            break;
        case UNDO_MAC:
            if (record->event.pressed) {
                if (os == OS_MACOS || os == OS_IOS) {
                    SEND_STRING(SS_LALT(SS_TAP(X_Z)));
                } else {
                    SEND_STRING(SS_LCTL("z"));
                }
            }
            break;
        case DEGR_MAC:
            if (record->event.pressed) {
                send_unicode_string("°");
            }
            break;
        case SEL_LN_MAC:
            if (record->event.pressed) {
                if (os == OS_MACOS || os == OS_IOS) {
                    SEND_STRING(SS_LCTL("a" SS_LSFT("e")));
                } else {
                    SEND_STRING(SS_TAP(X_HOME) SS_LSFT(SS_TAP(X_END)));
                }
            }
            break;
        case SEL_WD_MAC:
            if (record->event.pressed) {
                if (os == OS_MACOS || os == OS_IOS) {
                    SEND_STRING(SS_LCMD(SS_TAP(X_RIGHT) SS_LSFT(SS_TAP(X_LEFT))));
                } else {
                    SEND_STRING(SS_LCTL(SS_TAP(X_RIGHT) SS_LSFT(SS_TAP(X_LEFT))));
                }
            }
            break;
        case SEL_ALL_MAC:
            if (record->event.pressed) {
                if (os == OS_MACOS || os == OS_IOS) {
                    SEND_STRING(SS_LCMD("a"));
                } else {
                    SEND_STRING(SS_LCTL("a"));
                }
            }
            break;

    }
    return true;
}

